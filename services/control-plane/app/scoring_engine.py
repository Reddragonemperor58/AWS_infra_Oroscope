# Names that differ from the sheet but mean the same thing, found by diffing the
# live clinical_rules.provisional_diagnosis values against the sheet. Keys are
# already normalized (see _norm). CONFIRM the two marked clinical ones.
_ALIASES = {
    "noabnormalitydetected": "nothingabnormaldetected",
    "irritationfibroma": "fibroma",          # CONFIRM
    "apthousstomatitis": "apthousulcer",     # CONFIRM
}


def _norm(name: str) -> str:
    """Case-, whitespace- and apostrophe-insensitive key ('FIBRO EPITHELIAL POLYP' == ' Fibroepithelial Polyp')."""
    s = name.replace("\u2019", "'").casefold()
    return "".join(s.split())


_INDEX = {_norm(d): scores for d, scores in SCORE_TABLE.items()}


def get_band(deviation_score: float) -> str:
    dev = float(deviation_score)
    if dev < 0.16:
        return BAND_VARIABLE
    if dev <= 0.20:
        return BAND_BORDERLINE
    return BAND_SUGGESTIVE


def get_final_score(provisional_diagnosis: str, deviation_score: float) -> Optional[int]:
    """Returns the 0-5 score, or None if the diagnosis is not in the scoring sheet."""
    key = _norm(provisional_diagnosis)
    key = _ALIASES.get(key, key)
    scores = _INDEX.get(key)
    if scores is None:
        return None
    return scores[get_band(deviation_score)]